const MAP: Record<string, string> = {
  '—': '-', '–': '-', '…': '...', '★': '*', '’': "'", '‘': "'", '“': '"', '”': '"', è: 'e',
  à: 'a', ç: 'c', '✗': 'x', '❤': '♥', '×': 'x', '{': '(', '}': ')',
};

/** Replace characters the font cannot draw. Keeps length stable except for multi-char replacements. */
export function clean(s: string): string {
  let out = '';
  for (const ch of s) {
    const m = MAP[ch] ?? ch;
    for (const c of m) out += GLYPHS[c] ? c : c === '\n' ? '\n' : ' ';
  }
  return out;
}

